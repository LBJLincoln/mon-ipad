#!/usr/bin/env python3
"""Build TF predictions file from the Kaggle Oracle pkl (Brier 0.21383 best fold).

Replaces data/model-predictions-2025-26.json on the NBA TF Space with predictions
generated by the actual trained Oracle, NOT the 221-agent consensus that was
collapsing to coinflip.

Pipeline:
  1. Load all historical games in chronological order (2017-18 → 2025-26)
  2. Run features/engine.py NBAFeatureEngine.build() → (X, y, feature_names)
  3. Slice X[:, oracle_feature_indices] (200 features)
  4. Load nba-oracle.pkl, call predict_proba on the slice
  5. For each 2025-26 game, build per_category dict (mirroring extend_predictions logic)
  6. Save model-predictions-2025-26.json + push to TF Space
"""
from __future__ import annotations
import io, json, os, pickle, sys, time
from pathlib import Path
import numpy as np

ROOT = Path('/home/termius/mon-ipad')
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'hf-space'))  # alt feature engine location

from features.engine import NBAFeatureEngine

ORACLE_PKL = '/tmp/nba-oracle.pkl'  # downloaded from HF dataset
ORACLE_SUMMARY = '/tmp/oracle_summary.json'
GAMES_DIR = ROOT / 'data' / 'historical'
ODDS_CSV = ROOT / 'data' / 'historical-odds' / 'nba_2008-2025.csv'
TF_GAMES_FILE = '/tmp/tf_games.json'  # already pulled from TF
OUT_JSON = '/tmp/new_model_predictions.json'

# Empirical NBA variance (mirrored from extend_predictions_all_categories.py)
SIGMA_MARGIN = 12.0
SIGMA_TOTAL = 18.0
SIGMA_TEAM_TOTAL = 11.5


def _norm_cdf(x: float) -> float:
    import math
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def main() -> int:
    print('=== build_oracle_predictions ===', flush=True)
    t0 = time.time()

    # 1. Load Oracle pkl
    print(f'[1/6] Loading Oracle from {ORACLE_PKL}…', flush=True)
    if not Path(ORACLE_PKL).exists():
        sys.exit(f'ERROR: {ORACLE_PKL} missing — pull from HF dataset first.')
    with open(ORACLE_PKL, 'rb') as f:
        bundle = pickle.load(f)
    model = bundle['model']
    feature_indices = bundle['feature_indices']
    n_features_oracle = len(feature_indices)
    print(f'  oracle: type={type(model).__name__} n_features={n_features_oracle} '
          f'cv_brier={bundle.get("cv_brier_mean")} best_fold={bundle.get("best_fold_brier")}',
          flush=True)

    # 2. Load all historical games chronologically (in same order as cache build)
    print(f'[2/6] Loading historical games from {GAMES_DIR}…', flush=True)
    all_games = []
    season_files = sorted(GAMES_DIR.glob('games-*.json'))
    for f in season_files:
        try:
            raw = json.loads(f.read_text())
        except Exception as e:
            print(f'  skip {f.name}: {e}', flush=True)
            continue
        if isinstance(raw, list):
            all_games.extend(raw)
            print(f'  {f.name}: {len(raw)} games', flush=True)
        elif isinstance(raw, dict) and 'games' in raw:
            all_games.extend(raw['games'])
            print(f'  {f.name}: {len(raw["games"])} games', flush=True)
    print(f'  total: {len(all_games)} games', flush=True)

    # 3. Run feature engine
    print(f'[3/6] Running NBAFeatureEngine.build()… (may take 1-3 min)', flush=True)
    t1 = time.time()
    engine = NBAFeatureEngine()
    X, y, feature_names = engine.build(all_games)
    X = np.nan_to_num(np.array(X, dtype=np.float32))
    print(f'  built in {time.time()-t1:.1f}s: X.shape={X.shape} feat_count={len(feature_names)}', flush=True)
    if X.shape[1] < max(feature_indices) + 1:
        sys.exit(f'ERROR: engine has {X.shape[1]} feats but oracle needs index up to {max(feature_indices)}')

    # 4. Slice + predict (apply isotonic calibrator if present)
    print(f'[4/6] Slicing X to {n_features_oracle} oracle features and predicting…', flush=True)
    X_oracle = X[:, feature_indices]
    p_home_raw = model.predict_proba(X_oracle)[:, 1]  # P(home_win) raw
    calibrator = bundle.get('calibrator')
    if calibrator is not None:
        try:
            p_home_all = calibrator.predict(p_home_raw)
            print(f'  calibrated via isotonic: raw mean={p_home_raw.mean():.3f} → calibrated mean={p_home_all.mean():.3f}', flush=True)
        except Exception as e:
            print(f'  calibrator failed ({e}), using raw probs', flush=True)
            p_home_all = p_home_raw
    else:
        p_home_all = p_home_raw
    print(f'  predicted {len(p_home_all)} games. mean p_home={p_home_all.mean():.3f} '
          f'std={p_home_all.std():.3f} min={p_home_all.min():.3f} max={p_home_all.max():.3f}',
          flush=True)

    # 5. Build TF predictions for 2025-26 games only
    print(f'[5/6] Building per-game predictions for 2025-26 games…', flush=True)
    # The chronological build order = order of games in concatenated season files.
    # 2025-26 games = last (count) of all_games where game_date startswith '2025' or '2026'.
    s2526_indices = [i for i, g in enumerate(all_games)
                     if str(g.get('game_date', '')).startswith(('2025', '2026'))]
    print(f'  2025-26 row indices: {len(s2526_indices)} (first={s2526_indices[0] if s2526_indices else "?"} last={s2526_indices[-1] if s2526_indices else "?"})', flush=True)

    # Load TF's games list to get game_keys + matchup info
    tf_games_doc = json.loads(open(TF_GAMES_FILE).read())
    tf_games = tf_games_doc.get('games') or []
    print(f'  TF expects predictions for {len(tf_games)} 2025-26 games', flush=True)

    # Build per_game predictions dict keyed by f"{date}_{away}@{home}"
    out = {}
    matched = 0
    for i in s2526_indices:
        g = all_games[i]
        date = str(g.get('game_date', ''))[:10]
        home = (g.get('home_team') or g.get('home') or {}).get('team_abbr', '')
        away = (g.get('away_team') or g.get('away') or {}).get('team_abbr', '')
        if not (date and home and away):
            # try alt fields
            home = home or g.get('home', '')
            away = away or g.get('away', '')
        if not (date and home and away):
            continue
        gk = f'{date}_{away}@{home}'
        p_home = float(p_home_all[i])
        # Margin/total imputed from the original consensus would require market
        # data; for the oracle bridge we use NBA-average baselines + small tilt
        # from p_home so per_category logic still has predicted_margin and
        # predicted_total. Future improvement: train spread+total oracles.
        predicted_margin = (p_home - 0.5) * 8.0  # 1pp ≈ 0.16pt margin
        predicted_total = 224.0  # league avg
        # Build per_category from p_home + market odds (we don't have market here,
        # so we use predicted_p_home as the prob and edge=0 — TF parser will
        # recompute edge against full-odds-2025-26.json server-side). Actually:
        # the TF reads per_category[cat].edge directly. We must compute it as
        # predicted_prob − market_implied_prob. We'll defer that to settle when
        # we know we have full_odds for the game. For now, write the core fields.
        derived_core = {
            'predicted_p_home': round(p_home, 4),
            'predicted_margin': round(predicted_margin, 2),
            'predicted_total': round(predicted_total, 2),
        }
        # Build per_category (light version — the parser also re-derives from
        # full-odds-2025-26.json on the Space side, but TF reads edge here too)
        per_category = {
            'ml_home': {'prob': round(p_home, 4), 'edge': 0.0},  # filled at TF
            'ml_away': {'prob': round(1.0 - p_home, 4), 'edge': 0.0},
        }
        out[gk] = {
            'game_key': gk,
            'consensus_ml_direction': 'home' if p_home > 0.5 else 'away',
            'consensus_ml_confidence': round(abs(p_home - 0.5), 4),
            'consensus_ml_edge': 0.0,  # recomputed at TF against odds
            'consensus_spread_direction': 'home' if predicted_margin > 0 else 'away',
            'consensus_total_direction': 'over',
            'derived_core': derived_core,
            'per_category': per_category,
            'oracle_brier_cv': bundle.get('cv_brier_mean'),
            'oracle_n_features': n_features_oracle,
        }
        matched += 1

    print(f'  matched {matched}/{len(s2526_indices)} games', flush=True)

    # 6. Now extend per_category from full-odds (mirror of extend_predictions logic).
    # We pull full-odds-2025-26.json from TF, compute edge per category against
    # our oracle predicted_p_home (instead of consensus_ml_confidence tilt).
    print(f'[6/6] Extending per_category against full-odds…', flush=True)
    full_odds_path = '/tmp/tf_full_odds.json'
    if not Path(full_odds_path).exists():
        # Pull from TF Space
        import urllib.request
        tok = os.environ.get('HF_TOKEN_NBA') or os.environ.get('HF_TOKEN', '')
        url = 'https://huggingface.co/spaces/LBJLincoln26/nba-llm-trading-floor/resolve/main/data/full-odds-2025-26.json'
        req = urllib.request.Request(url, headers={'Authorization': f'Bearer {tok}'})
        with urllib.request.urlopen(req, timeout=60) as r:
            Path(full_odds_path).write_bytes(r.read())
    full_odds = json.loads(open(full_odds_path).read())
    print(f'  full_odds covers {len(full_odds)} games', flush=True)

    extended = 0
    for gk, pred in out.items():
        fo = full_odds.get(gk) or {}
        cats = (fo.get('categories') or fo) if isinstance(fo, dict) else {}
        if not isinstance(cats, dict):
            continue
        p_home = pred['derived_core']['predicted_p_home']
        margin = pred['derived_core']['predicted_margin']
        total = pred['derived_core']['predicted_total']
        per_cat = pred.setdefault('per_category', {})
        for cat_name, cat_data in cats.items():
            try:
                odds = float((cat_data or {}).get('odds') or (cat_data or {}).get('decimal_odds') or 0)
            except Exception:
                continue
            if odds <= 1.001:
                continue
            market_p = 1.0 / odds
            # Compute model_p per category
            model_p = None
            if cat_name == 'ml_home':
                model_p = p_home
            elif cat_name == 'ml_away':
                model_p = 1.0 - p_home
            elif cat_name == 'spread_home' or cat_name.startswith('alt_spread_home'):
                line = cat_data.get('line', 0) or 0
                model_p = _norm_cdf((margin + line) / SIGMA_MARGIN)
            elif cat_name == 'spread_away' or cat_name.startswith('alt_spread_away'):
                line = cat_data.get('line', 0) or 0
                model_p = _norm_cdf((-margin - line) / SIGMA_MARGIN)
            elif cat_name == 'total_over' or cat_name.startswith('alt_total_over'):
                line = cat_data.get('line', total) or total
                model_p = 1.0 - _norm_cdf((line - total) / SIGMA_TOTAL)
            elif cat_name == 'total_under' or cat_name.startswith('alt_total_under'):
                line = cat_data.get('line', total) or total
                model_p = _norm_cdf((line - total) / SIGMA_TOTAL)
            else:
                # halves/quarters/team_totals/props — use scaled approximation.
                # h1_* ≈ 0.5 of full margin/total, q1_* ≈ 0.25, etc.
                if cat_name.startswith('h1_'):
                    factor = 0.5
                elif cat_name.startswith('q1_') or cat_name.startswith('q2_') or cat_name.startswith('q3_') or cat_name.startswith('q4_'):
                    factor = 0.25
                else:
                    factor = 1.0
                if 'home' in cat_name and 'away' not in cat_name:
                    model_p = p_home if 'ml' in cat_name else None
                elif 'away' in cat_name:
                    model_p = (1.0 - p_home) if 'ml' in cat_name else None
                # if can't compute, leave model_p None
            if model_p is None or not (0 < model_p < 1):
                continue
            edge = round(model_p - market_p, 4)
            per_cat[cat_name] = {
                'prob': round(model_p, 4),
                'edge': edge,
            }
            if 'line' in (cat_data or {}):
                per_cat[cat_name]['line'] = cat_data['line']
        pred['category_count'] = len(per_cat)
        extended += 1

    print(f'  extended {extended} games with per_category from full-odds', flush=True)

    # 7. Save
    Path(OUT_JSON).write_text(json.dumps(out, indent=None))
    sz = Path(OUT_JSON).stat().st_size
    print(f'WROTE {OUT_JSON} ({sz/1024:.0f} KB) covering {len(out)} games', flush=True)
    print(f'TOTAL TIME: {time.time()-t0:.1f}s', flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())
